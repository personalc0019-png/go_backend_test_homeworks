package main

import "fmt"

func main() {
	a := 10
	b := 5

	//Сложение
	sum := a + b
	fmt.Println("Сумма:", sum)

	//Вычитание
	diff := a - b
	fmt.Println("Разность:", diff)

	//Умножение
	product := a * b
	fmt.Println("Произведение:", product)

	//Деление
	quotient := a / b
	fmt.Println("Частное:", quotient)

	sum1 := a + b
	fmt.Println("Сумма:", sum1)
}
